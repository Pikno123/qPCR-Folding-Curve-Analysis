function datasetName = get_dataset_name(filePath)


    [~, datasetName, ~] = fileparts(filePath);

    knownSuffixes = { ...
        '_temperature_folding_fit', ...
        '_integer_temperature_samples', ...
        '_aligned_temperature_windows', ...
        '_full_temperature_curves', ...
        '_thermodynamic_parameters', ...
        '_temperature_hill_input', ...
        '_temperature_filtered', ...
        '_adjacent_ratios', ...
        '_aligned_pH_windows', ...
        '_pH_hill_input', ...
        '_pH_transposed', ...
        '_reformatted'};

    suffixRemoved = true;
    while suffixRemoved
        suffixRemoved = false;
        for suffixIndex = 1:numel(knownSuffixes)
            suffix = knownSuffixes{suffixIndex};
            if length(datasetName) >= length(suffix) && strcmp(datasetName(end-length(suffix)+1:end), suffix)
                datasetName = datasetName(1:end-length(suffix));
                suffixRemoved = true;
                break;
            end
        end
    end
end
